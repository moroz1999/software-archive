-- Categories of software: one tree for every platform (docs/domain/categories.md).
CREATE TABLE category
(
    id        UUID PRIMARY KEY DEFAULT gen_random_uuid() NOT NULL,
    parent_id UUID REFERENCES category (id) ON DELETE CASCADE,
    title     TEXT                                       NOT NULL,
    -- The order among the children of the same parent.
    position  INT                                        NOT NULL
);

CREATE INDEX category_parent_id_idx ON category (parent_id);

-- Software in categories: deleting either side unlinks them.
CREATE TABLE software_category
(
    software_id UUID NOT NULL REFERENCES software (id) ON DELETE CASCADE,
    category_id UUID NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    PRIMARY KEY (software_id, category_id)
);

CREATE INDEX software_category_category_id_idx ON software_category (category_id);

