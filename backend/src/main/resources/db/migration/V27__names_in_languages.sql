-- Names kept in several languages: every one has a Russian name, the others are optional (docs/domain/localization.md).
CREATE TABLE language
(
    code TEXT PRIMARY KEY
);

INSERT INTO language (code)
VALUES ('en'),
       ('ru');

CREATE TABLE category_title
(
    category_id UUID NOT NULL REFERENCES category (id) ON DELETE CASCADE,
    language TEXT NOT NULL REFERENCES language (code),
    title TEXT NOT NULL,
    PRIMARY KEY (category_id, language)
);

CREATE TABLE country_name
(
    country_id UUID NOT NULL REFERENCES country (id) ON DELETE CASCADE,
    language TEXT NOT NULL REFERENCES language (code),
    name TEXT NOT NULL,
    PRIMARY KEY (country_id, language)
);

CREATE TABLE city_name
(
    city_id UUID NOT NULL REFERENCES city (id) ON DELETE CASCADE,
    language TEXT NOT NULL REFERENCES language (code),
    name TEXT NOT NULL,
    PRIMARY KEY (city_id, language)
);

CREATE TABLE platform_name
(
    platform_code TEXT NOT NULL REFERENCES platform (code) ON DELETE CASCADE,
    language TEXT NOT NULL REFERENCES language (code),
    name TEXT NOT NULL,
    PRIMARY KEY (platform_code, language)
);

CREATE TABLE hardware_name
(
    hardware_code TEXT NOT NULL REFERENCES hardware (code) ON DELETE CASCADE,
    language TEXT NOT NULL REFERENCES language (code),
    name TEXT NOT NULL,
    PRIMARY KEY (hardware_code, language)
);

